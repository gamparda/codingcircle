#!/usr/bin/env python3
"""Writes scripts/BattleRulesHash.gd: the SHA-256 of scripts/BattleModel.gd (line endings dropped), the same value
native/CMakeLists.txt compiles into the native battle engine. BattleModel uses the engine only when the two match,
so new rules in a game-data update fall back to GDScript until an app update brings a matching engine.

Run after every change to scripts/BattleModel.gd (tests/native_rules_hash_test.py checks it is current)."""
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]


def rules_hash() -> str:
    source = (ROOT / "scripts" / "BattleModel.gd").read_bytes().replace(b"\r", b"")
    return hashlib.sha256(source).hexdigest()


def render(value: str) -> str:
    return ('extends RefCounted\n'
            '## Generated by tools/update_rules_hash.py from scripts/BattleModel.gd: do not edit. The native battle\n'
            '## engine carries the same hash; BattleModel runs on it only when they match.\n\n'
            f'const HASH := "{value}"\n')


def main() -> int:
    target = ROOT / "scripts" / "BattleRulesHash.gd"
    text = render(rules_hash())
    if "--check" in sys.argv:
        return 0 if target.exists() and target.read_text(encoding="utf-8") == text else 1
    target.write_text(text, encoding="utf-8", newline="\n")
    print(rules_hash())
    return 0


if __name__ == "__main__":
    sys.exit(main())
